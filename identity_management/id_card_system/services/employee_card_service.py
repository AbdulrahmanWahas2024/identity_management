import frappe
from frappe import _
from frappe.utils import add_years, now_datetime, today


class EmployeeCardService:

    def __init__(self, doc):

        # مستند طلب البطاقة Card Request
        self.doc = doc

    # =====================================================
    # إنشاء بطاقة الموظف
    #
    # يتم استدعاؤها عند وصول الطلب إلى:
    # Card Preparation
    #
    # مسؤول تقنية المعلومات
    # =====================================================

    def create_identity_card(self):

        # منع إنشاء بطاقة مكررة لنفس الطلب

        if self.doc.employee_identity_card:

            return

        # إنشاء مستند بطاقة جديد

        card = frappe.new_doc("Employee Identity Card")

        # =====================================================
        # ربط البطاقة بطلب الإصدار
        # =====================================================

        card.card_request = self.doc.name

        # الموظف

        card.employee = self.doc.employee

        # الرقم الوظيفي الذي سيطبع على البطاقة

        card.employee_number = self.doc.employee_number

        # =====================================================
        # تحديد نوع البطاقة الافتراضي
        # =====================================================

        card.card_type = frappe.db.get_value("Card Type", {"is_default": 1}, "name")

        if not card.card_type:

            frappe.throw(_("لم يتم تعريف نوع بطاقة افتراضي."))

        # =====================================================
        # الحالة الابتدائية للبطاقة
        #
        # عند إنشاء البطاقة تكون:
        # بانتظار تقنية المعلومات
        # =====================================================

        card.card_status = "بانتظار تقنية المعلومات"

        # =====================================================
        # إنشاء رقم البطاقة
        #
        # مثال:
        # EMP-ID-26-00001
        #
        # هذا رقم البطاقة الصادرة
        # وليس رقم الطلب
        # =====================================================

        card.card_number = frappe.model.naming.make_autoname("EMP-ID-.YY.-.#####")

        # جهة الإصدار

        card.issuing_office = self.doc.branch

        # -------------------------------------------------
        # تاريخ الإصدار
        # -------------------------------------------------

        card.issue_date = today()

        # تاريخ انتهاء البطاقة
        # حالياً سنة واحدة.
        # يمكن لاحقاً جعلها إعداداً في Card Type.
        # -------------------------------------------------

        card.expiry_date = add_years(card.issue_date, 1)

        # -------------------------------------------------
        # تسجيل بداية التجهيز
        # -------------------------------------------------
        card.preparation_started_on = now_datetime()

        # حفظ البطاقة

        card.insert(ignore_permissions=True)

        # =====================================================
        # ربط البطاقة مع طلب الإصدار
        # =====================================================

        self.doc.db_set("employee_identity_card", card.name)

        frappe.msgprint(f"""
            <b>تم إنشاء بطاقة الموظف بنجاح</b>
            <br><br>
            رقم البطاقة:
            <b>{card.card_number}</b>
            <br>
            تاريخ الإصدار:
            <b>{card.issue_date}</b>
            <br>
            تاريخ الانتهاء:
            <b>{card.expiry_date}</b>
            """)

        return card

    # =====================================================
    # تحديث حالة البطاقة
    #
    # يتم استدعاؤها مع تغير Workflow
    #
    # مثال:
    #
    # Ready for Print
    # Printed
    # Delivered
    # Completed
    #
    # =====================================================
    # =====================================================
    # استلام الطلب من تقنية المعلومات
    #
    # يتم تسجيل:
    #
    # received_by
    # received_on
    # preparation_started_on
    #
    # =====================================================

    def receive_card_request(self):

        card = self.get_card()

        if not card:
            frappe.throw(_("لا توجد بطاقة مرتبطة بهذا الطلب."))

        # -------------------------------------------------
        # تسجيل الموظف الذي استلم الطلب
        # -------------------------------------------------

        card.received_by = frappe.session.user

        # -------------------------------------------------
        # تاريخ الاستلام
        # -------------------------------------------------

        card.received_on = now_datetime()

        # -------------------------------------------------
        # بداية التجهيز
        # -------------------------------------------------

        if not card.preparation_started_on:

            card.preparation_started_on = now_datetime()

        card.save(ignore_permissions=True)

        return card

    # =====================================================
    # تجهيز البطاقة
    #
    # يتم تنفيذها قبل Ready for Print
    #
    # =====================================================

    def prepare_card(self):

        card = self.get_card()

        if not card:

            frappe.throw(_("لا توجد بطاقة مرتبطة بهذا الطلب."))

        # -------------------------------------------------
        # التأكد من وجود الموظف
        # -------------------------------------------------

        if not card.employee:

            frappe.throw(_("لا يمكن تجهيز البطاقة بدون موظف."))

        # -------------------------------------------------
        # التأكد من الرقم الوظيفي
        # -------------------------------------------------

        if not card.employee_number:

            frappe.throw(_("لا يمكن تجهيز البطاقة بدون الرقم الوظيفي."))

        # -------------------------------------------------
        # التأكد من نوع البطاقة
        # -------------------------------------------------

        if not card.card_type:

            frappe.throw(_("لم يتم تحديد نوع البطاقة."))

        # -------------------------------------------------
        # التأكد من صورة الموظف
        # -------------------------------------------------

        if not card.employee_photo:

            frappe.throw(_("يجب إرفاق صورة الموظف قبل تجهيز البطاقة."))

        # -------------------------------------------------
        # التأكد من اعتماد الصورة
        # -------------------------------------------------

        if card.photo_status != "معتمدة":

            frappe.throw(_("لا يمكن تجهيز البطاقة لأن صورة الموظف " "لم يتم اعتمادها."))

        # -------------------------------------------------
        # تاريخ الإصدار
        # -------------------------------------------------

        if not card.issue_date:

            card.issue_date = today()

        # -------------------------------------------------
        # تاريخ الانتهاء
        # -------------------------------------------------

        if not card.expiry_date:

            card.expiry_date = add_years(card.issue_date, 1)

        # -------------------------------------------------
        # تسجيل انتهاء التجهيز
        # -------------------------------------------------

        card.preparation_completed_on = now_datetime()

        # -------------------------------------------------
        # حساب مدة التنفيذ
        # -------------------------------------------------

        if card.preparation_started_on:

            duration = card.preparation_completed_on - card.preparation_started_on

            card.processing_minutes = int(duration.total_seconds() / 60)

        # -------------------------------------------------
        # تغيير حالة البطاقة
        # -------------------------------------------------

        card.card_status = "جاهزة للطباعة"

        # -------------------------------------------------
        # حفظ البطاقة
        # -------------------------------------------------

        card.save(ignore_permissions=True)

        return card

    # =====================================================
    # جلب Employee Identity Card المرتبطة بالطلب
    # =====================================================

    def get_card(self):

        if not self.doc.employee_identity_card:

            return None

        return frappe.get_doc("Employee Identity Card", self.doc.employee_identity_card)

    # =====================================================
    # تحديث حالة البطاقة
    # =====================================================

    def update_card_status(self, status):

        # لا يوجد بطاقة مرتبطة

        if not self.doc.employee_identity_card:

            return

        frappe.db.set_value(
            "Employee Identity Card",
            self.doc.employee_identity_card,
            "card_status",
            status,
        )

    # =====================================================
    # التحقق النهائي قبل الطباعة
    #
    # لا يسمح النظام بالطباعة إلا بعد اكتمال
    # جميع متطلبات البطاقة.
    # =====================================================

    def validate_before_print(self):

        # -------------------------------------------------
        # الحصول على بطاقة الموظف
        # -------------------------------------------------

        card = self.get_card()

        if not card:

            frappe.throw(_("لا توجد بطاقة موظف مرتبطة بهذا الطلب."))

        # -------------------------------------------------
        # التحقق من الموظف
        # -------------------------------------------------

        if not card.employee:

            frappe.throw(_("لم يتم تحديد الموظف."))

        # -------------------------------------------------
        # التحقق من الرقم الوظيفي
        # -------------------------------------------------

        if not card.employee_number:

            frappe.throw(_("لم يتم تحديد الرقم الوظيفي."))

        # -------------------------------------------------
        # التحقق من نوع البطاقة
        # -------------------------------------------------

        if not card.card_type:

            frappe.throw(_("لم يتم تحديد نوع البطاقة."))

        # -------------------------------------------------
        # التحقق من صورة الموظف
        # -------------------------------------------------

        if not card.employee_photo:

            frappe.throw(_("يجب إرفاق صورة الموظف قبل الطباعة."))

        # -------------------------------------------------
        # التحقق من اعتماد الصورة
        # -------------------------------------------------

        if card.photo_status != "معتمدة":

            frappe.throw(_("لا يمكن طباعة البطاقة لأن صورة الموظف غير معتمدة."))

        # -------------------------------------------------
        # جميع الشروط مكتملة
        # -------------------------------------------------
        # =================================================
        # التحقق من تاريخ الإصدار
        # =================================================

        if not card.issue_date:
            frappe.throw(_("لا يمكن طباعة البطاقة: تاريخ الإصدار غير موجود."))

        # =================================================
        # التحقق من تاريخ الانتهاء
        # =================================================

        if not card.expiry_date:
            frappe.throw(_("لا يمكن طباعة البطاقة: تاريخ انتهاء البطاقة غير موجود."))

        # =================================================
        # تسجيل حركة التحقق
        # =================================================

        self.log_activity(
            card=card,
            activity_type="تحقق",
            remarks="تم التحقق من بيانات البطاقة والصورة قبل الطباعة.",
        )

        return True

    # =====================================================
    # تسجيل حركة في Card Activity Log
    # =====================================================

    def log_activity(self, card, activity_type, remarks=None):

        activity = frappe.new_doc("Card Activity Log")

        activity.employee_identity_card = card.name
        activity.employee = card.employee
        activity.activity_type = activity_type
        activity.activity_date = now_datetime()
        activity.performed_by = frappe.session.user
        activity.remarks = remarks or ""

        activity.insert(ignore_permissions=True)

        return activity
