import frappe
from frappe import _
from frappe.utils import add_years, now_datetime, today


class EmployeeCardService:

    def __init__(self, doc):

        # =================================================
        # مستند طلب البطاقة Card Request
        # =================================================

        self.doc = doc

    # =====================================================
    # إنشاء بطاقة الموظف
    # =====================================================

    def create_identity_card(self):

        # =================================================
        # منع إنشاء بطاقة مكررة
        # =================================================

        if self.doc.employee_identity_card:
            return self.get_card()

        # =================================================
        # إنشاء Employee Identity Card
        # =================================================

        card = frappe.new_doc("Employee Identity Card")

        # =================================================
        # ربط البطاقة بطلب الإصدار
        # =================================================

        card.card_request = self.doc.name

        # =================================================
        # الموظف
        # =================================================

        card.employee = self.doc.employee

        # =================================================
        # الرقم الوظيفي
        # =================================================

        card.employee_number = self.doc.employee_number

        # =================================================
        # صورة الموظف
        #
        # المصدر الأساسي:
        # Card Request
        # =================================================

        if self.doc.employee_photo:

            card.employee_photo = self.doc.employee_photo

            card.photo_status = self.doc.photo_status or "قيد المراجعة"

        else:

            card.employee_photo = None
            card.photo_status = "مطلوبة"

        # =================================================
        # نوع البطاقة الافتراضي
        # =================================================

        card.card_type = frappe.db.get_value(
            "Card Type",
            {"is_default": 1},
            "name",
        )

        if not card.card_type:

            frappe.throw(
                _("لم يتم تعريف نوع بطاقة افتراضي."),
                title=_("نوع البطاقة"),
            )

        # =================================================
        # حالة البطاقة الابتدائية
        # =================================================

        card.card_status = "بانتظار تقنية المعلومات"

        # =================================================
        # رقم البطاقة
        # =================================================

        card.card_number = frappe.model.naming.make_autoname("EMP-ID-.YY.-.#####")

        # =================================================
        # جهة الإصدار
        # =================================================

        card.issuing_office = self.doc.branch

        # =================================================
        # تاريخ الإصدار
        # =================================================

        card.issue_date = today()

        # =================================================
        # تاريخ الانتهاء
        # =================================================

        card.expiry_date = add_years(
            card.issue_date,
            1,
        )

        # =================================================
        # بداية التجهيز
        # =================================================

        card.preparation_started_on = now_datetime()

        # =================================================
        # حفظ البطاقة
        # =================================================

        card.insert(ignore_permissions=True)

        # =================================================
        # ربط البطاقة بطلب الإصدار
        # =================================================

        self.doc.db_set(
            "employee_identity_card",
            card.name,
        )

        return card

    # =====================================================
    # استلام الطلب من تقنية المعلومات
    #
    # مهم:
    # هذه الدالة أصبحت Idempotent
    #
    # أي إذا تم استدعاؤها أكثر من مرة بسبب حفظ الطلب
    # فلن تظهر رسالة:
    #
    # "تم استلام هذا الطلب مسبقًا"
    #
    # ولن تعيد تسجيل الاستلام.
    # =====================================================

    def receive_card_request(self):

        card = self.get_card()

        if not card:

            frappe.throw(
                _("لا توجد بطاقة مرتبطة بهذا الطلب."),
                title=_("بطاقة الموظف"),
            )

        # =================================================
        # إذا كان الطلب مستلمًا مسبقًا
        #
        # لا نعيد:
        # received_by
        # received_on
        # card_status
        #
        # ولا نسجل حركة استلام جديدة.
        #
        # فقط نزامن الصورة والحالة إذا احتاج الأمر.
        # =================================================

        if card.received_by:

            changed = False

            current_photo = self.doc.employee_photo or None

            current_status = self.doc.photo_status if current_photo else "مطلوبة"

            # ---------------------------------------------
            # مزامنة الصورة
            # ---------------------------------------------

            if card.employee_photo != current_photo:

                card.employee_photo = current_photo
                changed = True

            # ---------------------------------------------
            # مزامنة حالة الصورة
            # ---------------------------------------------

            if card.photo_status != current_status:

                card.photo_status = current_status
                changed = True

            # ---------------------------------------------
            # الحفظ فقط إذا حدث تغيير فعلي
            # ---------------------------------------------

            if changed:

                card.save(ignore_permissions=True)

            # ---------------------------------------------
            # مهم جدًا:
            # لا نعيد تسجيل الاستلام
            # ولا نغير حالة البطاقة.
            # ---------------------------------------------

            return card

        # =================================================
        # أول استلام فعلي للطلب
        # =================================================

        card.received_by = frappe.session.user

        # =================================================
        # وقت الاستلام
        # =================================================

        card.received_on = now_datetime()

        # =================================================
        # بداية التجهيز
        # =================================================

        if not card.preparation_started_on:

            card.preparation_started_on = now_datetime()

        # =================================================
        # حالة البطاقة
        # =================================================

        card.card_status = "قيد التجهيز"

        # =================================================
        # مزامنة الصورة من Card Request
        # =================================================

        self.sync_photo_to_card(card)

        # =================================================
        # حفظ البطاقة
        # =================================================

        card.save(ignore_permissions=True)

        # =================================================
        # تسجيل حركة الاستلام مرة واحدة فقط
        # =================================================

        self.log_activity(
            card=card,
            activity_type="استلام الطلب",
            remarks=(
                "تم استلام طلب إصدار البطاقة "
                "من قبل مختص تقنية المعلومات "
                "وبدء عملية التجهيز."
            ),
        )

        return card

    # =====================================================
    # مزامنة الصورة بين:
    #
    # Card Request
    #       ↓
    # Employee Identity Card
    #
    # =====================================================

    def sync_photo_to_card(self, card=None):

        if not card:

            card = self.get_card()

        if not card:

            frappe.throw(
                _("لا توجد بطاقة مرتبطة بهذا الطلب."),
                title=_("بطاقة الموظف"),
            )

        # =================================================
        # Card Request هو المصدر الأساسي للصورة
        # =================================================

        card.employee_photo = self.doc.employee_photo or None

        # =================================================
        # تحديد حالة الصورة
        # =================================================

        if self.doc.employee_photo:

            card.photo_status = self.doc.photo_status or "قيد المراجعة"

        else:

            card.photo_status = "مطلوبة"

        return card

    # =====================================================
    # تجهيز البطاقة
    #
    # Card Preparation
    #       ↓
    # تجهيز البطاقة
    #       ↓
    # Ready for Print
    # =====================================================

    def prepare_card(self):

        card = self.get_card()

        if not card:

            frappe.throw(
                _("لا توجد بطاقة مرتبطة بهذا الطلب."),
                title=_("بطاقة الموظف"),
            )

        # =================================================
        # التحقق من الموظف
        # =================================================

        if not card.employee:

            frappe.throw(
                _("لا يمكن تجهيز البطاقة بدون موظف."),
                title=_("الموظف"),
            )

        # =================================================
        # التحقق من الرقم الوظيفي
        # =================================================

        if not card.employee_number:

            frappe.throw(
                _("لا يمكن تجهيز البطاقة بدون الرقم الوظيفي."),
                title=_("الرقم الوظيفي"),
            )

        # =================================================
        # التحقق من نوع البطاقة
        # =================================================

        if not card.card_type:

            frappe.throw(
                _("لم يتم تحديد نوع البطاقة."),
                title=_("نوع البطاقة"),
            )

        # =================================================
        # التحقق من الصورة
        #
        # المصدر الأساسي = Card Request
        # =================================================

        self.validate_photo_for_processing()

        # =================================================
        # مزامنة الصورة والحالة
        # =================================================

        self.sync_photo_to_card(card)

        # =================================================
        # تاريخ الإصدار
        # =================================================

        if not card.issue_date:

            card.issue_date = today()

        # =================================================
        # تاريخ الانتهاء
        # =================================================

        if not card.expiry_date:

            card.expiry_date = add_years(
                card.issue_date,
                1,
            )

        # =================================================
        # انتهاء التجهيز
        # =================================================

        card.preparation_completed_on = now_datetime()

        # =================================================
        # حساب مدة التنفيذ
        # =================================================

        if card.preparation_started_on:

            duration = card.preparation_completed_on - card.preparation_started_on

            card.processing_minutes = int(duration.total_seconds() / 60)

        # =================================================
        # حالة البطاقة
        # =================================================

        card.card_status = "جاهزة للطباعة"

        # =================================================
        # حفظ
        # =================================================

        card.save(ignore_permissions=True)

        # =================================================
        # تسجيل الحركة
        # =================================================

        self.log_activity(
            card=card,
            activity_type="تجهيز البطاقة",
            remarks=(
                "تم التحقق من بيانات الموظف "
                "والصورة واعتمادها وتجهيز البطاقة للطباعة."
            ),
        )

        return card

    # =====================================================
    # التحقق من الصورة قبل التجهيز
    #
    # المصدر الأساسي = Card Request
    # =====================================================

    def validate_photo_for_processing(self):

        # =================================================
        # لا توجد صورة
        # =================================================

        if not self.doc.employee_photo:

            self.set_request_photo_status("مطلوبة")

            frappe.throw(
                _("لا يمكن تجهيز البطاقة: " "يجب إرفاق صورة الموظف أولاً."),
                title=_("صورة الموظف مطلوبة"),
            )

        # =================================================
        # قراءة حالة الصورة
        # =================================================

        photo_status = self.doc.photo_status

        # =================================================
        # الحالة فارغة
        # =================================================

        if not photo_status:

            self.set_request_photo_status("قيد المراجعة")

            frappe.throw(
                _("صورة الموظف موجودة " "ولكنها تحتاج إلى مراجعة واعتماد."),
                title=_("الصورة تحتاج اعتماد"),
            )

        # =================================================
        # قيد المراجعة
        # =================================================

        if photo_status == "قيد المراجعة":

            frappe.throw(
                _(
                    "لا يمكن تجهيز البطاقة: "
                    "صورة الموظف ما زالت قيد المراجعة.- يجب اعتماد الصورة"
                ),
                title=_("الصورة قيد المراجعة "),
            )

        # =================================================
        # مرفوضة
        # =================================================

        if photo_status == "مرفوضة":

            frappe.throw(
                _(
                    "لا يمكن تجهيز البطاقة: "
                    "تم رفض صورة الموظف. "
                    "يرجى رفع صورة جديدة ثم اعتمادها."
                ),
                title=_("الصورة مرفوضة"),
            )

        # =================================================
        # مطلوبة
        # =================================================

        if photo_status == "مطلوبة":

            frappe.throw(
                _("لا يمكن تجهيز البطاقة: " "يجب إرفاق صورة الموظف واعتمادها أولاً."),
                title=_("الصورة مطلوبة"),
            )

        # =================================================
        # أي حالة أخرى غير معتمدة
        # =================================================

        if photo_status != "معتمدة":

            frappe.throw(
                _("لا يمكن تجهيز البطاقة: " "يجب اعتماد صورة الموظف أولاً."),
                title=_("الصورة غير معتمدة"),
            )

        return True

    # =====================================================
    # التحقق قبل الانتقال إلى Ready for Print
    # =====================================================

    def validate_request_before_print(self):

        # =================================================
        # الموظف
        # =================================================

        if not self.doc.employee:

            frappe.throw(
                _("لا يمكن تجهيز البطاقة بدون تحديد الموظف."),
                title=_("الموظف"),
            )

        # =================================================
        # الرقم الوظيفي
        # =================================================

        if not self.doc.employee_number:

            frappe.throw(
                _("لا يمكن تجهيز البطاقة بدون الرقم الوظيفي."),
                title=_("الرقم الوظيفي"),
            )

        # =================================================
        # التحقق من الصورة
        # =================================================

        self.validate_photo_for_processing()

        # =================================================
        # الحصول على البطاقة
        # =================================================

        card = self.get_card()

        if not card:

            frappe.throw(
                _("لا توجد بطاقة موظف مرتبطة بهذا الطلب."),
                title=_("بطاقة الموظف"),
            )

        # =================================================
        # نوع البطاقة
        # =================================================

        if not card.card_type:

            frappe.throw(
                _("لم يتم تحديد نوع البطاقة."),
                title=_("نوع البطاقة"),
            )

        # =================================================
        # مزامنة الصورة والحالة
        # =================================================

        card.employee_photo = self.doc.employee_photo
        card.photo_status = "معتمدة"

        # =================================================
        # تاريخ الإصدار
        # =================================================

        if not card.issue_date:

            card.issue_date = today()

        # =================================================
        # تاريخ الانتهاء
        # =================================================

        if not card.expiry_date:

            card.expiry_date = add_years(
                card.issue_date,
                1,
            )

        # =================================================
        # حفظ
        # =================================================

        card.save(ignore_permissions=True)

        # =================================================
        # تسجيل الحركة
        # =================================================

        self.log_activity(
            card=card,
            activity_type="تحقق من الصورة",
            remarks=(
                "تم التحقق من وجود صورة الموظف "
                "واعتمادها في طلب البطاقة "
                "قبل الانتقال إلى الطباعة."
            ),
        )

        return True

    # =====================================================
    # جلب Employee Identity Card
    # =====================================================

    def get_card(self):

        if not self.doc.employee_identity_card:

            return None

        return frappe.get_doc(
            "Employee Identity Card",
            self.doc.employee_identity_card,
        )

    # =====================================================
    # رفع أو تغيير صورة الموظف
    #
    # تتم العملية من Card Request
    #
    # هذه الدالة مهمة جدًا لمرحلة:
    #
    # Card Preparation
    # =====================================================

    def update_employee_photo(self, photo):

        if not photo:

            frappe.throw(
                _("يجب إرفاق صورة الموظف."),
                title=_("الصورة مطلوبة"),
            )

        # =================================================
        # تحديث Card Request
        # =================================================

        self.doc.employee_photo = photo
        self.doc.photo_status = "قيد المراجعة"

        self.doc.db_set(
            "employee_photo",
            photo,
        )

        self.doc.db_set(
            "photo_status",
            "قيد المراجعة",
        )

        # =================================================
        # تحديث Employee Identity Card
        # =================================================

        card = self.get_card()

        if card:

            card.employee_photo = photo
            card.photo_status = "قيد المراجعة"

            card.save(ignore_permissions=True)

            # =================================================
            # تسجيل الحركة
            # =================================================

            self.log_activity(
                card=card,
                activity_type="رفع صورة",
                remarks=("تم رفع أو تحديث صورة الموظف " "من قبل مختص تقنية المعلومات."),
            )

        return card

    # =====================================================
    # اعتماد صورة الموظف
    #
    # تتم من Card Request
    # =====================================================

    def approve_photo(self):

        # =================================================
        # التأكد من وجود الصورة
        # =================================================

        if not self.doc.employee_photo:

            frappe.throw(
                _("يجب إرفاق صورة الموظف قبل اعتمادها."),
                title=_("الصورة مطلوبة"),
            )

        # =================================================
        # تحديث حالة الصورة في Card Request
        # =================================================

        self.doc.photo_status = "معتمدة"

        self.doc.db_set(
            "photo_status",
            "معتمدة",
        )

        # =================================================
        # الحصول على البطاقة
        # =================================================

        card = self.get_card()

        if not card:

            frappe.throw(
                _("لا توجد بطاقة موظف مرتبطة بهذا الطلب."),
                title=_("بطاقة الموظف"),
            )

        # =================================================
        # تحديث Employee Identity Card
        # =================================================

        card.employee_photo = self.doc.employee_photo
        card.photo_status = "معتمدة"

        card.save(ignore_permissions=True)

        # =================================================
        # تسجيل الحركة
        # =================================================

        self.log_activity(
            card=card,
            activity_type="اعتماد صورة",
            remarks=("تم اعتماد صورة الموظف " "من قبل مختص تقنية المعلومات."),
        )

        return card

    # =====================================================
    # تحديث حالة البطاقة
    # =====================================================

    def update_card_status(self, status):

        card = self.get_card()

        if not card:

            return

        # =================================================
        # لا تحفظ إذا كانت الحالة نفسها
        # =================================================

        if card.card_status == status:

            return

        card.card_status = status

        card.save(ignore_permissions=True)

    # =====================================================
    # التحقق النهائي قبل الطباعة
    #
    # المصدر الأساسي:
    # Card Request
    # =====================================================

    def validate_before_print(self):

        # =================================================
        # الموظف
        # =================================================

        if not self.doc.employee:

            frappe.throw(
                _("لم يتم تحديد الموظف."),
                title=_("الموظف"),
            )

        # =================================================
        # الرقم الوظيفي
        # =================================================

        if not self.doc.employee_number:

            frappe.throw(
                _("لم يتم تحديد الرقم الوظيفي."),
                title=_("الرقم الوظيفي"),
            )

        # =================================================
        # البطاقة
        # =================================================

        card = self.get_card()

        if not card:

            frappe.throw(
                _("لا توجد بطاقة موظف مرتبطة بهذا الطلب."),
                title=_("بطاقة الموظف"),
            )

        # =================================================
        # نوع البطاقة
        # =================================================

        if not card.card_type:

            frappe.throw(
                _("لم يتم تحديد نوع البطاقة."),
                title=_("نوع البطاقة"),
            )

        # =================================================
        # الصورة
        # =================================================

        if not self.doc.employee_photo:

            frappe.throw(
                _("لا يمكن طباعة البطاقة: " "يجب إرفاق صورة الموظف."),
                title=_("صورة الموظف مطلوبة"),
            )

        # =================================================
        # حالة الصورة
        # =================================================

        if self.doc.photo_status != "معتمدة":

            if self.doc.photo_status == "مطلوبة":

                message = "لا يمكن طباعة البطاقة: " "صورة الموظف لم يتم رفعها."

                title = "الصورة مطلوبة"

            elif self.doc.photo_status == "قيد المراجعة":

                message = "لا يمكن طباعة البطاقة: " "صورة الموظف ما زالت قيد المراجعة."

                title = "الصورة قيد المراجعة"

            elif self.doc.photo_status == "مرفوضة":

                message = "لا يمكن طباعة البطاقة: " "صورة الموظف مرفوضة."

                title = "الصورة مرفوضة"

            else:

                message = "لا يمكن طباعة البطاقة: " "صورة الموظف غير معتمدة."

                title = "الصورة غير معتمدة"

            frappe.throw(
                _(message),
                title=_(title),
            )

        # =================================================
        # مزامنة الصورة والحالة
        # =================================================

        card.employee_photo = self.doc.employee_photo
        card.photo_status = "معتمدة"

        # =================================================
        # تاريخ الإصدار
        # =================================================

        if not card.issue_date:

            card.issue_date = today()

        # =================================================
        # تاريخ الانتهاء
        # =================================================

        if not card.expiry_date:

            card.expiry_date = add_years(
                card.issue_date,
                1,
            )

        # =================================================
        # حفظ
        # =================================================

        card.save(ignore_permissions=True)

        # =================================================
        # تسجيل التحقق
        # =================================================

        self.log_activity(
            card=card,
            activity_type="تحقق",
            remarks=(
                "تم التحقق من بيانات الطلب " "وصورة الموظف واعتمادها قبل الطباعة."
            ),
        )

        return True

    # =====================================================
    # تحديث حالة الصورة في Card Request
    # =====================================================

    def set_request_photo_status(self, status):

        self.doc.photo_status = status

        self.doc.db_set(
            "photo_status",
            status,
        )

    # =====================================================
    # تسجيل الحركة
    # =====================================================

    def log_activity(
        self,
        card,
        activity_type,
        remarks=None,
    ):

        activity = frappe.new_doc("Card Activity Log")

        activity.employee_identity_card = card.name

